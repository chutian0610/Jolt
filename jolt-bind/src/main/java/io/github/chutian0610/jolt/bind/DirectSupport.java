package io.github.chutian0610.jolt.bind;

import io.github.chutian0610.jolt.JoltParser;
import io.github.chutian0610.jolt.Token;
import io.github.chutian0610.jolt.tree.TypeTag;
import io.github.chutian0610.jolt.Utf16Parser;
import io.github.chutian0610.jolt.Utf8Parser;

import java.util.ArrayDeque;

/**
 * The co-located home of the direct read's shared semantics: the error helpers both direct
 * grades call, and the shared per-thread state (the lazy path carrier, the parser pair, the
 * scratch pools, the seen flags). The reflective direct binder calls the explicit-path
 * cores; the generated direct read's bytecode calls the public wrappers via INVOKESTATIC —
 * one implementation of the declaration-order contract and the message shapes, so the two
 * grades cannot drift.
 *
 * <p>The public surface exists for the generated bytecode: the generated class loads in a
 * different runtime package than jolt-bind. The path-bearing helpers come in two shapes by
 * consumer, not by generation: the {@link BindPath}-parameterized cores (the reflective
 * binder calls them with its own carrier; the M8 generated form loads its baked carrier
 * slot), and the thread-resolving forms the shared error/numeric emission and the reference
 * arm use (one shape, two forms' shared emission — not a doubling).
 */
public final class DirectSupport {

    private static final ThreadLocal<DirectState> STATE = ThreadLocal.withInitial(DirectState::new);

    private DirectSupport() {}

    // --- the shared per-thread state (package-private: jolt-bind's own call sites) ---

    static BindPath statePath() {
        return STATE.get().path;
    }

    static JoltParser parserFor(byte[] json) {
        return STATE.get().parserFor(json);
    }

    static JoltParser parserFor(String json) {
        return STATE.get().parserFor(json);
    }

    static Object[] takeBuffer() {
        return STATE.get().takeBuffer();
    }

    static void returnBuffer(Object[] buffer) {
        STATE.get().returnBuffer(buffer);
    }

    // --- the public door (the generated direct read's INVOKESTATIC targets) ---

    /** Resets the thread's path carrier (the generated read's entry step). */
    public static void resetPath() {
        STATE.get().path.reset();
    }

    /** Pushes a field name onto the thread's path carrier. */
    public static void pushName(String name) {
        STATE.get().path.pushName(name);
    }

    /** Pops the current path segment. */
    public static void pop() {
        STATE.get().path.pop();
    }

    /**
     * The collection reads' recovery after an element failure (#61): the cursor sits inside
     * {@code depth} open containers (between children); consume through their closers,
     * nested containers included, so the enclosing field loop stays aligned — the scalar
     * tag rejection's container skip, at collection scale. EOF ends it (a truncated document
     * surfaces as the parser's own error on the next read).
     */
    public static void drainContainer(JoltParser p, int depth) {
        while (depth > 0) {
            Token t = p.nextToken();
            if (t == Token.START_OBJECT || t == Token.START_ARRAY) {
                depth++;
            } else if (t == Token.END_OBJECT || t == Token.END_ARRAY) {
                depth--;
            } else if (t == Token.EOF) {
                return;
            }
        }
    }

    // --- the per-parse carrier (the M8 generated body: ONE ThreadLocal lookup per parse) ---

    /**
     * The thread's path carrier, reset for a new document root and handed to the generated
     * body: the M8 body resolves it ONCE per parse and threads it through its field and
     * element loops, where the M7 body re-resolved the ThreadLocal on every
     * {@code pushName}/{@code pop} — the dissection's machinery cost (#55, #57).
     */
    public static BindPath resetCarrier() {
        BindPath path = STATE.get().path;
        path.reset();
        return path;
    }

    /** The thread's carrier at its current position — the nested body form (the caller
     * owns the position). */
    public static BindPath takeCarrier() {
        return STATE.get().path;
    }

    /**
     * The M8 inline loops' error edge, from the component handler: every segment the loops
     * pushed above {@code savedDepth} is one container the failure left the cursor inside of
     * (an index per list/array level, a key per map level — a child element's body pops its
     * own segments before its sweep raises), so drain exactly that many closers, then
     * restore the carrier. A failure outside any loop (depth unchanged) drains nothing.
     */
    public static void recoverCollection(BindPath carrier, int savedDepth, JoltParser p) {
        BindPath path = (BindPath) carrier;
        int inside = path.depth() - savedDepth;
        if (inside > 0) {
            drainContainer(p, inside);
        }
        path.truncate(savedDepth);
    }

    /** The array scratch pool, for the generated inline array loops (the door's own
     * {@code readArray} takes it through the package-private twins). */
    public static Object[] takeArrayScratch() {
        return STATE.get().takeBuffer();
    }

    /** Returns the array scratch (element references released by the caller). */
    public static void returnArrayScratch(Object[] buffer) {
        STATE.get().returnBuffer(buffer);
    }

    /** The seen-flag scratch: pooled per-thread (nesting takes its own array). The caller
     * zeroes the array before use — pooled content is stale by design. */
    public static boolean[] takeSeen(int length) {
        return STATE.get().takeSeen(length);
    }

    /** Returns the seen-flag scratch to the thread's pool. */
    public static void returnSeen(boolean[] seen) {
        STATE.get().returnSeen(seen);
    }

    /** The tree layer's tag-rejection message at the CURRENT path position. A container
     * value is skipped before the throw so the field loop stays aligned. */
    public static RuntimeException tagError(JoltParser p, Token t, String wanted) {
        return tagError(p, t, wanted, STATE.get().path);
    }

    /** VALUE_NUMBER_INT or the promotion-strategy overflow message — the shared long read. */
    public static long readLongChecked(JoltParser p, Token t) {
        return readLongChecked(p, t, STATE.get().path);
    }

    /** VALUE_NUMBER_INT or VALUE_NUMBER_FLOAT at the CURRENT path position, else the tag
     * rejection. */
    public static void requireNumber(JoltParser p, Token t) {
        requireNumber(p, t, STATE.get().path);
    }

    /** JSON null against a primitive component — the shared throw. */
    public static RuntimeException nullForPrimitive(String simpleName) {
        return nullForPrimitive(simpleName, STATE.get().path);
    }

    /** The shared width-overflow throw (message from the component's getSimpleName). */
    public static RuntimeException boundError(String simpleName) {
        return boundError(simpleName, STATE.get().path);
    }

    /** The BigInteger fraction rejection ("number is not a whole number"). */
    public static RuntimeException notWholeNumber() {
        return notWholeNumber(STATE.get().path);
    }

    /** The unknown-enum-name rejection at the CURRENT path position. */
    public static RuntimeException unknownEnumName(String text, String simpleName) {
        return unknownEnumName(text, simpleName, STATE.get().path);
    }

    /** The canonical constructor rejected the bound values — the raw cause is interpolated
     * exactly like the reflective arm's {@code getCause()} message. */
    public static RuntimeException constructorRejected(Throwable cause) {
        return constructorRejected(cause, STATE.get().path);
    }

    /**
     * Records a component error in the lazily-allocated slot array (the failure path may
     * allocate — ADR-0005); returns the array to store back. The generated bytecode calls
     * this after catching {@link JsonBindException} around a component read.
     */
    public static Object[] noteError(Object[] errors, int slot, JsonBindException e,
                                     int componentCount) {
        Object[] out = errors != null ? errors : new Object[componentCount];
        out[slot] = e;
        return out;
    }

    /**
     * The unknown-field shared semantics: materializes the FIRST unknown key's name only
     * when strict mode demands it (and only once), then consumes the value. Returns the
     * updated recorded key.
     */
    public static String skipOrNoteUnknown(JoltParser p, BindConfig config, String recorded) {
        if (config.failOnUnknown() && recorded == null) {
            recorded = p.textValue();
        }
        skipValue(p);
        return recorded;
    }

    /**
     * The record body's error sweep, shared by both direct grades: declaration-order slot
     * errors, then missing primitives, then the first unknown field — the tree path's
     * raising order, at the CURRENT path position. Returns normally when the body may
     * construct.
     */
    public static void sweepRecordErrors(Object[] errors, boolean[] seen, String unknownKey,
                                         String[] names, boolean[] primitives,
                                         String[] simpleNames) {
        sweepRecordErrors(errors, seen, unknownKey, STATE.get().path,
                names, primitives, simpleNames);
    }

    /** A non-object document root against an all-reference record: the spectrum tickets'
     * honest marker, shared verbatim by both direct grades. */
    public static RuntimeException nonObjectRecordRoot() {
        throw new UnsupportedOperationException(
                "all-reference records bind from non-object documents with the M6 spectrum tickets");
    }

    /**
     * The nested door: the child's body read for a value whose START_OBJECT the caller
     * already consumed (the child continues the caller's cursor; the caller owns the path
     * position, the error slotting, and the drain). This is the reflective arm of the
     * generated parent's nested dispatch — used when the child has no emitted direct body.
     * Recursion converges through the per-class binder cache (self-referential records
     * terminate on finite documents).
     */
    public static Object nestedBody(JoltParser p, BindConfig config, Class<?> childType) {
        DirectBinder<?> child = DirectBinder.forClass(childType);
        return child.readBody(p, config, STATE.get().path, Token.START_OBJECT);
    }

    /**
     * The value-read door for the generated arm's delegated reads (collection elements,
     * map values, untyped Object): the caller consumed the value's first token and holds
     * the path position; the element Type is the parent's baked constant. The Plan resolves
     * once per Type (the per-call reflection the M6-T4 plan refactor removed stays gone).
     */
    public static Object readValue(JoltParser p, Token first, java.lang.reflect.Type targetType,
                                   BindConfig config) {
        return DirectBinder.readValue(p, first, DirectBinder.planFor(targetType), config,
                STATE.get().path);
    }

    /** The guarded setter invoke's rejection, at the CURRENT path position — the raw cause
     * interpolates exactly like the reflective arm's {@code getCause()} message. RETURNS
     * the exception (it does not throw): the generated read's handler passes it to ATHROW,
     * the reflective body slots it with {@code noteError}. */
    public static JsonBindException setterRejected(Throwable cause) {
        return setterRejected(cause, STATE.get().path);
    }

    /** The no-arg construction failure ("cannot instantiate"), at the CURRENT path
     * position. */
    public static RuntimeException cannotInstantiate(String typeName) {
        return cannotInstantiate(typeName, STATE.get().path);
    }

    /**
     * The POJO body's error sweep, shared by both direct grades: declaration-order slot
     * errors, then the first unknown field — absent properties stay default (there is no
     * missing check), at the CURRENT path position.
     */
    public static void sweepPojoErrors(Object[] errors, String unknownKey) {
        sweepPojoErrors(errors, unknownKey, STATE.get().path);
    }

    // --- the explicit-path cores (the reflective direct binder's call sites) ---

    /** The tree layer's tag-rejection message at the value's path. A container value is
     * skipped before the throw so the field loop stays aligned. */
    static RuntimeException tagError(JoltParser p, Token t, String wanted, BindPath path) {
        if (t == Token.START_OBJECT || t == Token.START_ARRAY) {
            p.skipChildren();
        }
        throw new JsonBindException(
                BindErrorText.expectedButFound(wanted, tagName(t)), path.resolve());
    }

    /**
     * The shared long read, the tree arm's {@code asLong} semantics: an integer-form token
     * takes the fast path; a decimal-form token is accepted when its exact value fits a
     * long ({@code 1.0 → 1L}) and rejected with the SAME overflow message otherwise — the
     * two read paths are one error matrix (CONTEXT.md). The wide form only materializes on
     * the decimal branch (rare; the failure path may allocate — ADR-0005).
     */
    static long readLongChecked(JoltParser p, Token t, BindPath path) {
        if (t == Token.VALUE_NUMBER_INT) {
            try {
                return p.longValue();
            } catch (ArithmeticException beyondLong) {
                throw new JsonBindException(BindErrorText.LONG_OVERFLOW, path.resolve());
            }
        }
        if (t != Token.VALUE_NUMBER_FLOAT) {
            throw tagError(p, t, BindErrorText.A_NUMBER, path);
        }
        try {
            return p.bigDecimalValue().longValueExact();
        } catch (ArithmeticException beyondLong) {
            throw new JsonBindException(BindErrorText.LONG_OVERFLOW, path.resolve());
        }
    }

    /** VALUE_NUMBER_INT or VALUE_NUMBER_FLOAT, else the tag rejection. */
    static void requireNumber(JoltParser p, Token t, BindPath path) {
        if (t != Token.VALUE_NUMBER_INT && t != Token.VALUE_NUMBER_FLOAT) {
            throw tagError(p, t, BindErrorText.A_NUMBER, path);
        }
    }

    /** JSON null against a primitive component — the shared throw. */
    static RuntimeException nullForPrimitive(String simpleName, BindPath path) {
        throw new JsonBindException(BindErrorText.nullForPrimitive(simpleName), path.resolve());
    }

    /** The shared width-overflow throw (message from the component's getSimpleName). */
    static RuntimeException boundError(String simpleName, BindPath path) {
        throw new JsonBindException(BindErrorText.boundError(simpleName), path.resolve());
    }

    /** The BigInteger fraction rejection. */
    static RuntimeException notWholeNumber(BindPath path) {
        throw new JsonBindException(BindErrorText.NOT_WHOLE_NUMBER, path.resolve());
    }

    /** The unknown-enum-name rejection. */
    static RuntimeException unknownEnumName(String text, String simpleName, BindPath path) {
        throw new JsonBindException(BindErrorText.unknownEnumName(text, simpleName),
                path.resolve());
    }

    /** The canonical constructor rejected the bound values. */
    static RuntimeException constructorRejected(Throwable cause, BindPath path) {
        throw new JsonBindException(BindErrorText.constructorRejected(cause), path.resolve());
    }

    /** The guarded setter invoke's rejection. */
    static JsonBindException setterRejected(Throwable cause, BindPath path) {
        return new JsonBindException(BindErrorText.setterRejected(cause), path.resolve());
    }

    /** The no-arg construction failure. */
    static RuntimeException cannotInstantiate(String typeName, BindPath path) {
        throw new JsonBindException(BindErrorText.cannotInstantiate(typeName), path.resolve());
    }

    /**
     * The POJO body's error sweep core: declaration-order slot errors, then the first
     * unknown field — absent properties stay default (there is no missing check).
     */
    static void sweepPojoErrors(Object[] errors, String unknownKey, BindPath path) {
        if (errors != null) {
            for (int i = 0; i < errors.length; i++) {
                if (errors[i] instanceof JsonBindException e) {
                    throw e;
                }
            }
        }
        if (unknownKey != null) {
            throw new JsonBindException(BindErrorText.unknownField(unknownKey),
                    path.resolve() + "." + unknownKey);
        }
    }

    /**
     * The record body's error sweep core: declaration-order slot errors, then missing
     * primitives, then the first unknown field.
     */
    static void sweepRecordErrors(Object[] errors, boolean[] seen, String unknownKey,
                                  BindPath path, String[] names, boolean[] primitives,
                                  String[] simpleNames) {
        for (int i = 0; i < names.length; i++) {
            if (errors != null && errors[i] instanceof JsonBindException e) {
                throw e;
            }
            if (!seen[i] && primitives[i]) {
                throw new JsonBindException(BindErrorText.missingValueForPrimitive(simpleNames[i]),
                        path.resolve() + "." + names[i]);
            }
        }
        if (unknownKey != null) {
            throw new JsonBindException(BindErrorText.unknownField(unknownKey),
                    path.resolve() + "." + unknownKey);
        }
    }

    /**
     * The found-part of a tag rejection: DERIVED from the tree layer's own {@link TypeTag}
     * name, never hand-copied — a TypeTag rename follows, a Token addition fails to compile.
     */
    private static String tagName(Token t) {
        return switch (t) {
            case VALUE_STRING -> TypeTag.STRING.name();
            case VALUE_NUMBER_INT, VALUE_NUMBER_FLOAT -> TypeTag.NUMBER.name();
            case VALUE_TRUE, VALUE_FALSE -> TypeTag.BOOLEAN.name();
            case VALUE_NULL -> TypeTag.NULL.name();
            case START_OBJECT, FIELD_NAME -> TypeTag.OBJECT.name();
            case START_ARRAY -> TypeTag.ARRAY.name();
            default -> throw new IllegalStateException("unexpected token " + t);
        };
    }

    private static void skipValue(JoltParser p) {
        Token t = p.nextToken();
        if (t == Token.START_OBJECT || t == Token.START_ARRAY) {
            p.skipChildren();
        }
    }

    /** Per-thread parser pair, path stack, array scratch pool, and seen-flag scratch (the
     * M1 reuse discipline, applied to binding). Lives here so both direct grades — and the
     * generated bytecode through the statics above — consume the identical state. */
    private static final class DirectState {
        final BindPath path = new BindPath();
        private final ArrayDeque<Object[]> bufferPool = new ArrayDeque<>();
        private final ArrayDeque<boolean[]> seenPool = new ArrayDeque<>();
        private Utf8Parser utf8;
        private Utf16Parser utf16;

        boolean[] takeSeen(int length) {
            boolean[] pooled = seenPool.pollFirst();
            if (pooled != null && pooled.length >= length) {
                return pooled;
            }
            if (pooled != null) {
                seenPool.addFirst(pooled); // too small for this body — back to the pool
            }
            return new boolean[Math.max(length, 8)];
        }

        void returnSeen(boolean[] seen) {
            if (seenPool.size() < 8) {
                seenPool.addFirst(seen);
            }
        }

        Object[] takeBuffer() {
            Object[] buffered = bufferPool.pollFirst();
            return buffered != null ? buffered : new Object[8];
        }

        void returnBuffer(Object[] buffer) {
            if (bufferPool.size() < 8) {
                bufferPool.addFirst(buffer);
            }
        }

        JoltParser parserFor(byte[] json) {
            if (utf8 == null) {
                utf8 = io.github.chutian0610.jolt.Jolt.utf8Parser(json);
                return utf8;
            }
            return utf8.reset(json);
        }

        JoltParser parserFor(String json) {
            if (utf16 == null) {
                utf16 = io.github.chutian0610.jolt.Jolt.utf16Parser(json);
                return utf16;
            }
            return utf16.reset(json);
        }
    }
}
