package io.github.chutian0610.jolt.bind;

import org.junit.jupiter.api.Test;

import java.util.Collection;
import java.util.Date;
import java.util.Deque;
import java.util.List;
import java.util.Map;
import java.util.Set;

import static org.junit.jupiter.api.Assertions.assertEquals;

/**
 * The shape classification's exhaustive table: every raw-class family maps to its one
 * {@link BindingShape} — the same decision the tree path, the direct read, and jolt-gen's
 * capability predicate all consume. The {@code java.*} pins matter most: a concrete JDK
 * class binds as a POJO on every read path (the capability layer, not the shape, refuses
 * generated bytecode for it).
 */
class BindingShapeTest {

    public enum Color { RED, BLUE }

    public record Point(int x, int y) {}

    public static class Plain {
        public int v;
    }

    abstract static class Abstractish {}

    interface Shapeless {}

    @Test
    void textAndBoolean() {
        assertEquals(BindingShape.TEXT, BindingShape.of(String.class));
        assertEquals(BindingShape.BOOLEAN, BindingShape.of(boolean.class));
        assertEquals(BindingShape.BOOLEAN, BindingShape.of(Boolean.class));
    }

    @Test
    void everyNumericWidth() {
        Class<?>[] widths = {byte.class, Byte.class, short.class, Short.class,
                int.class, Integer.class, long.class, Long.class,
                float.class, Float.class, double.class, Double.class};
        for (Class<?> width : widths) {
            assertEquals(BindingShape.NUMBER, BindingShape.of(width), width.getSimpleName());
        }
        assertEquals(BindingShape.NUMBER, BindingShape.of(java.math.BigDecimal.class));
        assertEquals(BindingShape.NUMBER, BindingShape.of(java.math.BigInteger.class));
        assertEquals(BindingShape.isNumber(int.class), true);
    }

    @Test
    void enumAndRecord() {
        assertEquals(BindingShape.ENUM, BindingShape.of(Color.class));
        assertEquals(BindingShape.RECORD, BindingShape.of(Point.class));
    }

    @Test
    void arraysOfEveryDepth() {
        assertEquals(BindingShape.ARRAY, BindingShape.of(int[].class));
        assertEquals(BindingShape.ARRAY, BindingShape.of(String[].class));
        assertEquals(BindingShape.ARRAY, BindingShape.of(Point[][].class));
    }

    @Test
    void exactListAndMapRaws() {
        assertEquals(BindingShape.LIST, BindingShape.of(List.class));
        assertEquals(BindingShape.MAP, BindingShape.of(Map.class));
    }

    @Test
    void naturalIsObjectOnly() {
        assertEquals(BindingShape.NATURAL, BindingShape.of(Object.class));
    }

    @Test
    void concreteClassesArePojo_includingJdk() {
        assertEquals(BindingShape.POJO, BindingShape.of(Plain.class));
        // the java.* pins: binding semantics, not capability — a concrete JDK class is a POJO
        assertEquals(BindingShape.POJO, BindingShape.of(Date.class));
        assertEquals(BindingShape.POJO, BindingShape.of(StringBuilder.class));
    }

    @Test
    void polymorphicRefusals() {
        assertEquals(BindingShape.UNBOUND, BindingShape.of(Shapeless.class));
        assertEquals(BindingShape.UNBOUND, BindingShape.of(Abstractish.class));
        // the other collection interfaces: not the exact whitelist, refused as always
        assertEquals(BindingShape.UNBOUND, BindingShape.of(Set.class));
        assertEquals(BindingShape.UNBOUND, BindingShape.of(Collection.class));
        assertEquals(BindingShape.UNBOUND, BindingShape.of(Deque.class));
    }
}
